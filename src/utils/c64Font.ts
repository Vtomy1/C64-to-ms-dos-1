// Render string onto a 320x200 8-bit chunky buffer (like VGA Mode 13h)
export function renderC64Text(
  buffer: Uint8Array,
  text: string,
  charX: number,
  charY: number,
  colorIndex: number
) {
  const pixelStartX = charX * 8;
  const pixelStartY = charY * 8;

  for (let c = 0; c < text.length; c++) {
    const ascii = text.charCodeAt(c);
    const upperAscii = (ascii >= 97 && ascii <= 122) ? ascii - 32 : ascii;
    const glyph = C64_FONT_8X8[upperAscii] || C64_FONT_8X8[32];
    const targetX = pixelStartX + c * 8;

    if (targetX + 8 > 320) break;

    for (let row = 0; row < 8; row++) {
      const rowByte = glyph[row] || 0;
      const py = pixelStartY + row;
      if (py >= 200) break;

      for (let col = 0; col < 8; col++) {
        if ((rowByte & (0x80 >> col)) !== 0) {
          const px = targetX + col;
          if (px < 320) {
            buffer[py * 320 + px] = colorIndex;
          }
        }
      }
    }
  }
}
